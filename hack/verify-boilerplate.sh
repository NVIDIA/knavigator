# Checks that every file in the repository starts with the canonical header:
# the two SPDX lines followed by the Apache-2.0 notice, as in this file. Go
# files carry it as a /* ... */ block; every other file as "#" comments, after
# the shebang line if there is one. The copyright year is YYYY or YYYY-YYYY.
#
# Every tracked file is checked, and so is every untracked file that git does
# not ignore, so a new file fails before it is staged. Files that cannot or
# should not carry the header are listed in "exclude" below, each with the
# reason.
#
# Usage: hack/verify-boilerplate.sh [REPO_ROOT]
# Exit codes: 0 all files pass, 1 a file fails, 2 nothing could be checked.

set -o errexit -o nounset -o pipefail

root=${1:-$(cd "$(dirname "$0")/.." && pwd)}

# Bash glob patterns matched against the path from the repository root. "*"
# also matches "/".
exclude=(
	# Formats with no comment syntax.
	'*.json' # Grafana dashboards in resources/dashboards
	'*.csv'  # trace data in resources/traces
	'*.png'

	# Documentation and project metadata, which carry no license header.
	'*.md'
	'LICENSE' # the license text itself
	'OWNERS'
	'SECURITY_CONTACTS'
	'.github/CODEOWNERS'

	# Helm charts: comments in templates render into the manifests (and
	# NOTES.txt into the install output), and the tests directories hold the
	# helm-unittest suites and the snapshots it generates.
	'charts/*/templates/*'
	'charts/*/tests/*'

	# Maintained by tools.
	'go.mod' # rewritten by the go command
	'go.sum'
	'.gitignore'           # ignore patterns only
	'charts/*/.helmignore' # generated by helm create, ignore patterns only

	# Third-party content: a terminal color scheme copied from
	# iTerm2-Color-Schemes, whose comment marker is "!".
	'.xresources'

	# Pending: open pull requests change these files. Remove each entry, and
	# add or align the header, once its pull request merges.
	'.github/workflows/helm.yml'   # NVIDIA/knavigator#227
	'.github/workflows/stale.yaml' # NVIDIA/knavigator#226
)

copyright_re='^(# | \* )SPDX-FileCopyrightText: Copyright \(c\) (.*) NVIDIA CORPORATION & AFFILIATES\. All rights reserved\.$'
year_re='^[0-9]{4}(-[0-9]{4})?$'

# The Apache-2.0 notice after the copyright line, without comment markers.
notice=(
	'SPDX-License-Identifier: Apache-2.0'
	''
	'Licensed under the Apache License, Version 2.0 (the "License");'
	'you may not use this file except in compliance with the License.'
	'You may obtain a copy of the License at'
	''
	'    http://www.apache.org/licenses/LICENSE-2.0'
	''
	'Unless required by applicable law or agreed to in writing, software'
	'distributed under the License is distributed on an "AS IS" BASIS,'
	'WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.'
	'See the License for the specific language governing permissions and'
	'limitations under the License.'
)

is_excluded() {
	local pattern
	for pattern in "${exclude[@]}"; do
		# shellcheck disable=SC2053 # the right-hand side is a glob on purpose
		[[ $1 == $pattern ]] && return 0
	done
	return 1
}

# check_file PATH prints one line naming the first problem in PATH's header
# and returns 1, or returns 0 if the header is canonical.
check_file() {
	local path=$1 prefix='# ' blank='#' line year want got i k n=0
	local -a head=()

	# The header is at most 16 lines, after at most one shebang line.
	while ((${#head[@]} < 17)) && { IFS= read -r line || [[ -n $line ]]; }; do
		head+=("$line")
	done <"$root/$path"

	# n is the index of the copyright line: after "/*" in Go files, after the
	# shebang line in the others.
	if [[ $path == *.go ]]; then
		prefix=' * ' blank=' *' n=1
	elif [[ ${head[0]-} == '#!'* ]]; then
		n=1
	fi

	got=${head[n]-}
	if [[ $got != *SPDX-FileCopyrightText* ]]; then
		for ((k = 0; k < ${#head[@]}; k++)); do
			if [[ ${head[k]} == *SPDX-FileCopyrightText* ]]; then
				echo "$path: SPDX-FileCopyrightText on line $((k + 1)), want line $((n + 1))"
				return 1
			fi
		done
		echo "$path: missing SPDX header"
		return 1
	fi
	if [[ $path == *.go && ${head[0]} != '/*' ]]; then
		echo "$path:1: want \"/*\", got \"${head[0]}\""
		return 1
	fi
	if [[ ! $got =~ $copyright_re || ${BASH_REMATCH[1]} != "$prefix" ]]; then
		want="${prefix}SPDX-FileCopyrightText: Copyright (c) YYYY NVIDIA CORPORATION & AFFILIATES. All rights reserved."
		echo "$path:$((n + 1)): want \"$want\", got \"$got\""
		return 1
	fi
	year=${BASH_REMATCH[2]}
	if [[ ! $year =~ $year_re ]]; then
		echo "$path: copyright year \"$year\" is not YYYY or YYYY-YYYY"
		return 1
	fi

	for i in "${!notice[@]}"; do
		n=$((n + 1))
		want=$prefix${notice[i]}
		[[ -z ${notice[i]} ]] && want=$blank
		got=${head[n]-}
		if [[ $got != "$want" ]]; then
			echo "$path:$((n + 1)): want \"$want\", got \"$got\""
			return 1
		fi
	done

	if [[ $path == *.go && ${head[n + 1]-} != ' */' ]]; then
		echo "$path:$((n + 2)): want \" */\", got \"${head[n + 1]-}\""
		return 1
	fi
	return 0
}

if ! files=$(git -C "$root" -c core.quotePath=false ls-files --cached --others --exclude-standard 2>/dev/null); then
	echo "verify-boilerplate: $root is not a git work tree" >&2
	exit 2
fi
if [[ -z $files ]]; then
	echo "verify-boilerplate: no files to check in $root" >&2
	exit 2
fi

checked=0 excluded=0 bad=0
while IFS= read -r path; do
	# A tracked file deleted from the work tree has nothing to check.
	[[ -f $root/$path ]] || continue
	if is_excluded "$path"; then
		excluded=$((excluded + 1))
		continue
	fi
	checked=$((checked + 1))
	check_file "$path" || bad=$((bad + 1))
done < <(LC_ALL=C sort -u <<<"$files")

if ((bad > 0)); then
	echo "FAIL: $bad of $checked files checked, $excluded excluded. Copy the header from a file of the same type, or add an exclusion with a reason to hack/verify-boilerplate.sh."
	exit 1
fi
echo "OK: $checked files checked, $excluded excluded."
